package dev.constructive.eo.demo.uplc

import scala.util.{Failure, Success, Try}

import dev.constructive.eo.demo.uplc.runtime.{Discharge, Dispatch, ProgramInfo, Rt}
import java.util.concurrent.{ExecutionException, FutureTask}
import scalus.cardano.ledger.ExUnits
import scalus.uplc.builtin.Data
import scalus.uplc.eval.{Log, MachineError, Result}
import scalus.uplc.{Constant, Term}

/** Runs a class file produced by [[UplcJvm]]. */
object Exec:

  /** Generated code recurses on the JVM stack where the CEK machine uses the heap, so evaluations
    * run on a dedicated thread with a large stack.
    */
  private val StackSize = 512L * 1024 * 1024

  final private class DefiningLoader(parent: ClassLoader) extends ClassLoader(parent):

    def define(bytes: Array[Byte]): Class[?] =
      defineClass(Lower.ClassName.replace('/', '.'), bytes, 0, bytes.length)

  /** Defines the class in a fresh loader (one per load: the class name is fixed). The JVM verifies
    * the generated bytecode here, as it does every class an application loader defines.
    */
  def load(classFile: Array[Byte]): Dispatch = loaded(classFile)._1

  private def loaded(classFile: Array[Byte]): (Dispatch, ProgramInfo) =
    val cls = new DefiningLoader(getClass.getClassLoader).define(classFile)
    (
      cls.getField("INSTANCE").get(null).asInstanceOf[Dispatch],
      cls.getField("INFO").get(null).asInstanceOf[ProgramInfo]
    )

  /** Evaluates the program, then applies the resulting value to `args` — the way the ledger applies
    * a validator to its script context, and the same order the CEK machine follows for
    * `[[program] arg]`. The outcome is Scalus' own evaluation `Result`, with the value discharged
    * to a de Bruijn term (comparable with the CEK's by `α_==`) and no budget: nothing is metered.
    */
  def run(classFile: Array[Byte], args: Seq[Constant] = Nil): Result = onLargeStack {
    val log = new Log
    val (program, info) = loaded(classFile)
    Rt.logs.set(log)
    // An evaluation's one way out on failure (see `Rt`), and the one place it becomes a value.
    val outcome = Try(args.foldLeft(program.run())(Rt.apply))
    Rt.logs.remove()
    val logs = log.getLogs.toList
    outcome match
      case Success(value) => Result.Success(Discharge(value, info), ExUnits.zero, Map.empty, logs)
      case Failure(bug: AssertionError) => throw bug // a compiler bug is not the program's failure
      case Failure(e)                   =>
        val error =
          if e.isInstanceOf[StackOverflowError] then MachineError("JVM stack exhausted") else e
        Result.Failure(error, ExUnits.zero, Map.empty, logs)
  }

  /** Plutus V3 validation (CIP-117): the script applied to its context must succeed with unit. */
  def validate(classFile: Array[Byte], scriptContext: Data): Either[String, Seq[String]] =
    run(classFile, List(Constant.Data(scriptContext))) match
      case Result.Success(Term.Const(Constant.Unit, _), _, _, logs) => Right(logs)
      case Result.Success(other, _, _, _)                           =>
        Left(s"script returned a non-unit value: ${other.show}")
      case Result.Failure(e, _, _, _) => Left(e.getMessage.nn)

  private[uplc] def onLargeStack[A](body: => A): A =
    val task = new FutureTask[A](() => body)
    val thread = new Thread(null, task, "uplc-jvm", StackSize)
    thread.start()
    thread.join()
    try task.get()
    catch case e: ExecutionException => throw e.getCause
